#!/usr/bin/env bash
# Guards on the node quote API this image serves (SUP-922).
#
# `pki-vm-measurements` gained `POST /v1/getQuote`, which returns TEE evidence
# over report data the CALLER chooses. That is exactly the credential the swarm
# PKI authority issues a node certificate against, so the one property that
# makes the endpoint safe is that it cannot be reached from off the node:
# the service binds it to 127.0.0.1, and this image must not open it.
#
# Why that needs a guard here and not only in tee-pki: hardening-vm.sh inserts
#   iptables -I INPUT -s 10.42.0.0/16 -j ACCEPT   (pod CIDR, and 10.43/10.13)
# at the HEAD of a DROP-policy INPUT chain, with its own `@TODO this will
# ignore NetworkPolicies in k8s`. So anything the node binds on a routable
# address is reachable by a tenant pod regardless of NetworkPolicy. An
# `iptables -A INPUT -p tcp --dport 9181 -j ACCEPT` added here "for symmetry
# with 9180" would hand that pod a mintable PKI credential, and nothing else
# in the tree would notice.
#
# Runs against the repository tree (rootfs-tests.yml, every PR) and, with
# SP_QUOTE_TEST_INSTALLED_ROOT, against the installed rootfs from src/Dockerfile
# — where it also checks that the pin bump actually put the endpoint in the
# image.

set -uo pipefail

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
repository_root="$(cd -- "$script_dir/../../.." && pwd)"
config_dir="$repository_root/src/rootfs/files/configs"
pin_dir="$config_dir/npm/pki-components"

if [[ -n "${SP_QUOTE_TEST_INSTALLED_ROOT:-}" ]]; then
    hardening="$SP_QUOTE_TEST_INSTALLED_ROOT/usr/local/bin/hardening-vm.sh"
    installed_package="$SP_QUOTE_TEST_INSTALLED_ROOT/usr/local/lib/pki-components/node_modules/@super-protocol/pki-vm-measurements"
    # src/Dockerfile ADDs the two pin files here, not into the output root:
    # install_pki_components.sh deletes them from the rootfs after `npm ci`.
    pin_dir="${SP_QUOTE_TEST_PIN_DIR:-/buildroot/files/configs/npm/pki-components}"
else
    hardening="$config_dir/usr/local/bin/hardening-vm.sh"
    installed_package=""
fi

# The version that first served /v1/getQuote. Below it the swarm-cloud-api
# statement signer has nothing to delegate to and the cloud serves no
# attestation bundle at all (SUP-922).
readonly required_version="1.2.0"
readonly quote_port="9181"
readonly measure_port="9180"

failures=0
fail() { echo "FAIL: $*" >&2; failures=$((failures + 1)); }
ok() { echo "ok: $*"; }

# True when $1 >= $2 under version ordering.
version_at_least() {
    [[ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -n1)" == "$2" ]]
}

# Deliberately grep and sed rather than a JSON parser: this suite runs inside
# the image build too, where bash and coreutils are all that is guaranteed.
# Both files are generated by npm and have one dependency per line.
quoted_value() { grep -oE '"[^"]+"$' | tr -d '"'; }

# The dependency SPEC. Unique in either file as a key with no path prefix: the
# lock's own entry is keyed "node_modules/@super-protocol/pki-vm-measurements".
pinned_spec() {
    grep -oE '"@super-protocol/pki-vm-measurements": *"[^"]+"' "$1" | head -n1 | quoted_value
}

# The version npm resolved that spec to, from the lock's package entry.
locked_entry_version() {
    sed -n '/"node_modules\/@super-protocol\/pki-vm-measurements": {/,/}/p' "$1" \
        | grep -oE '"version": *"[^"]+"' | head -n1 | quoted_value
}

# Top-level "version" of an installed package manifest; npm writes it second,
# after "name".
manifest_version() {
    [[ -r "$1" ]] || return 0
    grep -oE '"version": *"[^"]+"' "$1" | head -n1 | quoted_value
}

# --- the firewall must not open the quote port ------------------------------

if [[ -r "$hardening" ]]; then
    if grep -qE "^iptables -A INPUT -p tcp --dport ${quote_port} -j ACCEPT" "$hardening"; then
        fail "hardening-vm.sh opens :${quote_port}. The quote API binds loopback and must stay" \
            "unreachable off the node: a quote over caller-chosen report data is an issuable PKI" \
            "credential, and the pod-CIDR ACCEPT at the head of this chain bypasses NetworkPolicy."
    else
        ok "hardening-vm.sh leaves :${quote_port} closed"
    fi

    # The measurements/health port is deliberately open with no source
    # restriction, and safe because its report data is 64 zero bytes. Asserted
    # so the two ports cannot be confused for each other later.
    grep -qE "^iptables -A INPUT -p tcp --dport ${measure_port} -j ACCEPT" "$hardening" \
        || fail "hardening-vm.sh no longer opens :${measure_port}, which the fabric and the host orchestrator need"

    # The delegation channel is 127.0.0.1 from a --network=host container, so
    # this rule is what makes it work at all.
    grep -qx 'iptables -A INPUT -i lo -j ACCEPT' "$hardening" \
        || fail "hardening-vm.sh must accept loopback: the API container reaches the quote API over 127.0.0.1"
else
    fail "hardening-vm.sh not found at $hardening"
fi

# --- the pinned version must be one that serves the endpoint ----------------

pinned="$(pinned_spec "$pin_dir/package.json")"

if [[ -z "$pinned" ]]; then
    fail "cannot read the pki-vm-measurements pin from $pin_dir/package.json"
elif version_at_least "$pinned" "$required_version"; then
    ok "pki-vm-measurements pinned at $pinned"
else
    fail "pki-vm-measurements is pinned at $pinned, below $required_version, which first served" \
        "/v1/getQuote. swarm-cloud-api fails closed without it and the cloud serves no bundle."
fi

# A lock that disagrees with the manifest fails `npm ci` inside the image
# build, which is an expensive place to find a one-line edit.
locked_spec="$(pinned_spec "$pin_dir/package-lock.json")"
locked_version="$(locked_entry_version "$pin_dir/package-lock.json")"

if [[ -z "$locked_spec" || -z "$locked_version" ]]; then
    fail "cannot read the pki-vm-measurements entry from $pin_dir/package-lock.json"
elif [[ "$locked_spec" == "$pinned" && "$locked_version" == "$pinned" ]]; then
    ok "package-lock.json agrees with the pin"
else
    fail "package-lock.json has pki-vm-measurements as spec '$locked_spec' resolved to" \
        "'$locked_version', but package.json pins '$pinned'." \
        "Regenerate with 'npm install --package-lock-only' in $pin_dir."
fi

# --- and the image must actually carry it -----------------------------------

if [[ -n "$installed_package" ]]; then
    if [[ -d "$installed_package" ]]; then
        installed="$(manifest_version "$installed_package/package.json")"
        if version_at_least "${installed:-0}" "$required_version"; then
            ok "installed pki-vm-measurements is $installed"
        else
            fail "the image installed pki-vm-measurements ${installed:-<unknown>}, below $required_version"
        fi
        [[ -f "$installed_package/dist/quote-api.js" ]] \
            || fail "the installed package has no dist/quote-api.js, so no node on this image can serve a quote"
        grep -q "quotePort: ${quote_port}" "$installed_package/conf/default.yaml" \
            || fail "the installed conf/default.yaml does not set quotePort: ${quote_port}; the unit passes no override, so the listener would be off"
        grep -q '127\.0\.0\.1' "$installed_package/dist/quote-api.js" \
            || fail "the installed quote API does not bind 127.0.0.1"
    else
        fail "pki-vm-measurements is not installed at $installed_package"
    fi
fi

if (( failures > 0 )); then
    echo "$failures test(s) failed" >&2
    exit 1
fi
echo "all quote API exposure tests passed"
